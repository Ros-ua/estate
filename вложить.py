# -*- coding: utf-8 -*-
"""Вложить состояние моделей прямо в страницу.

Зачем: страница, которая ходит в сеть за своими же данными, ломается там,
где обращения режут — у блокировщиков и в строгих настройках браузера.
Проверено 25.08: зарубилось даже чтение соседнего файла на том же сайте.
Поэтому данные вкладываем внутрь, а сеть оставляем запасным путём.
"""
import io
import re
import sys

MARK = re.compile(r"/\*СЮДА-СОСТОЯНИЕ\*/.*?/\*КОНЕЦ\*/", re.S)

data = io.open("status.json", encoding="utf-8").read().strip()
p = "status.html"
t = io.open(p, encoding="utf-8").read()

# Отсутствие метки — настоящая поломка. Совпадение содержимого — норма.
if not MARK.search(t):
    sys.exit("ОШИБКА: метки для вложения нет в " + p)

t2 = MARK.sub(lambda _: "/*СЮДА-СОСТОЯНИЕ*/" + data + "/*КОНЕЦ*/", t, count=1)
if t2 == t:
    print("состояние в странице уже свежее — менять нечего")
else:
    io.open(p, "w", encoding="utf-8").write(t2)
    print("состояние вложено в страницу")
